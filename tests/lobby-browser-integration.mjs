import { navigateTo, navigationItem as nav } from "./browser-navigation.mjs";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { createClient } from "@libsql/client";

assert.equal(process.env.PAVILION_TEST_ISOLATED, "1", "Use the isolated API runner, never a user's auction database.");
const { chromium } = await import(pathToFileURL(resolve(process.env.PLAYWRIGHT_MODULE || ".sites-runtime/browser-tools/node_modules/playwright/index.mjs")));
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || "C:/Program Files/BraveSoftware/Brave-Browser/Application/brave.exe", headless: true });
const database = createClient({ url: process.env.DATABASE_URL, timeout: 100 });
const base = process.env.BASE_URL;
const screenshots = resolve(".sites-runtime/screenshots");
await mkdir(screenshots, { recursive: true });
const errors = [], requests = [];
const context = async (width = 1440) => {
  const context = await browser.newContext({ viewport: { width, height: width > 1000 ? 1000 : 844 } });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => requests.push({ url: new URL(request.url()).pathname, method: request.method() }));
  return { context, page };
};
const clickNav = async (page, name) => {
  await navigateTo(page, name);
};
const counts = async () => (await database.execute("SELECT (SELECT COUNT(*) FROM auction_rooms) AS rooms, (SELECT COUNT(*) FROM catalog_editor_sessions) AS editors")).rows[0];
const overflow = page => page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth);
const roomAccess = (page, code) => page.evaluate(code => JSON.parse(localStorage.getItem(`pavilion-session-${code}`)), code);
const roomState = async (access) => {
  const response = await fetch(`${base}/api/rooms/${access.code}`, { headers: { Authorization: `Bearer ${access.token}` } });
  assert.equal(response.status, 200);
  return (await response.json()).state;
};

try {
  const before = await counts();
  const { page: host } = await context();
  const { page: owner } = await context();
  await host.goto(`${base}/?practice=1&view=squads`);
  await nav(host, "Home").waitFor();
  assert.equal(new URL(host.url()).search, "");
  assert.deepEqual(await host.locator('nav[aria-label="Main navigation"] button > span:first-of-type').allTextContents(), ["Home", "Player pool"]);
  assert.equal(await host.locator(".room-dock, .practice-bar, .auction-layout, .metrics").count(), 0);
  assert.equal(await host.locator(".cinematic-cast-player img").count(), 8);
  assert.equal(await host.locator("video").count(), 0);
  await host.locator(".cinematic-cast-player img").evaluateAll(images => Promise.all(images.map(image => image.decode())));
  await host.evaluate(() => document.fonts.ready);
  assert.equal(await overflow(host), false);
  await host.screenshot({ path: resolve(screenshots, "lobby-home-1440.png"), fullPage: true });
  await clickNav(host, /Player pool/);
  await host.getByRole("heading", { name: /Player pool/ }).waitFor();
  assert.equal(await host.getByRole("button", { name: "Select", exact: true }).count(), 0);
  assert.equal(await host.getByLabel("Filter player status").count(), 0);
  await owner.goto(`${base}/?view=players`);
  await owner.getByRole("heading", { name: /Player pool/ }).waitFor();
  assert.deepEqual(await counts(), before, "visiting Home/Pool must not create fake rooms or editor credentials");
  assert.equal(requests.filter(request => request.url === "/api/practice").length, 0);
  console.log("PASS: Home has only Home/Pool, old practice and restricted links normalize, and browsing creates no rooms.");

  // A lobby editor can add a shared player, and an unrelated browser receives it.
  await host.getByRole("button", { name: "Add player", exact: true }).click();
  await host.getByRole("button", { name: "Enter player manually" }).click();
  const editor = host.getByRole("dialog", { name: "Add a player", exact: true });
  await editor.getByLabel("Player name", { exact: true }).fill("Lobby Browser Signing");
  await editor.getByLabel("Country", { exact: true }).fill("India");
  await editor.locator("select").first().selectOption("Batter");
  await editor.getByRole("button", { name: "Add player", exact: true }).click();
  await editor.waitFor({ state: "hidden" });
  await host.getByLabel("Search player name or country").fill("Lobby Browser Signing");
  await host.getByRole("button", { name: "View details for Lobby Browser Signing", exact: true }).waitFor();
  await owner.getByLabel("Search player name or country").fill("Lobby Browser Signing");
  await owner.bringToFront();
  await owner.getByRole("button", { name: "View details for Lobby Browser Signing", exact: true }).waitFor();
  await host.reload();
  await host.getByLabel("Search player name or country").fill("Lobby Browser Signing");
  await host.getByRole("button", { name: "View details for Lobby Browser Signing", exact: true }).waitFor();
  assert.equal((await counts()).rooms, before.rooms);
  console.log("PASS: lobby editing syncs to an independent browser and survives refresh without creating an auction.");

  await clickNav(host, "Home");
  await host.getByRole("button", { name: "Create an auction", exact: true }).click();
  let dialog = host.getByRole("dialog", { name: "Create auction room", exact: true });
  await dialog.getByLabel("Your name", { exact: true }).fill("Browser Host");
  await dialog.getByLabel("Room name", { exact: true }).fill("Lobby navigation verification");
  await dialog.getByRole("button", { name: "Create auction room", exact: true }).click();
  await nav(host, "Team squads").waitFor();
  const code = new URL(host.url()).searchParams.get("room");
  const hostAccess = await roomAccess(host, code);
  assert.ok(hostAccess?.token);
  const accessResponse = await fetch(`${base}/api/rooms/${code}/access`, { method: "POST", headers: { Authorization: `Bearer ${hostAccess.token}`, "Content-Type": "application/json" }, body: "{}" });
  assert.equal(accessResponse.status, 200);
  const { teamPassword } = await accessResponse.json();
  assert.equal((await counts()).rooms, Number(before.rooms) + 1);
  await owner.goto(`${base}/?room=${code}`);
  dialog = owner.getByRole("dialog", { name: "Join auction room", exact: true });
  await dialog.waitFor();
  await owner.reload();
  await dialog.waitFor();
  assert.equal(await dialog.getByLabel("Room code", { exact: true }).inputValue(), code);
  await dialog.getByLabel("Your name", { exact: true }).fill("Browser Owner");
  await dialog.locator("select").selectOption("rcb");
  await dialog.getByLabel("Team password", { exact: true }).fill(teamPassword);
  await dialog.getByRole("button", { name: "Join auction room", exact: true }).click();
  await nav(owner, "My Squad").waitFor();
  const ownerAccess = await roomAccess(owner, code);
  await clickNav(owner, "My Squad");
  await owner.getByRole("heading", { name: "Your first signing starts here.", exact: true }).waitFor();
  await clickNav(host, /Player pool/);
  await host.getByLabel("Search player name or country").fill("Lobby Browser Signing");
  await host.getByRole("button", { name: "Select", exact: true }).click();
  await host.locator(".auction-layout").waitFor();
  assert.equal(new URL(host.url()).searchParams.get("view"), "room");
  assert.match(await host.locator(".player-bio h2").textContent(), /Lobby Browser\s*Signing/);
  await host.getByRole("button", { name: "Open the bidding", exact: true }).click();
  await clickNav(owner, "Auction room");
  await owner.getByRole("button", { name: "Raise to ₹50 L", exact: true }).click();
  await clickNav(owner, "My Squad");
  assert.equal(await owner.locator(".personal-squad-player").count(), 0, "bids alone must not enter a squad");
  await host.getByRole("button", { name: "Lock bidding", exact: true }).click();
  await host.getByRole("button", { name: "Sell to RCB", exact: true }).click();
  await owner.bringToFront();
  await owner.getByRole("heading", { name: "Lobby Browser Signing", exact: true }).waitFor();
  assert.equal(await owner.locator(".personal-squad-purchase strong").innerText(), "₹50 L");
  const purchased = await roomState(ownerAccess);
  const rcb = purchased.teams.find(team => team.id === "rcb");
  assert.equal(rcb.squad.length, 1);
  assert.equal(rcb.squad[0].amount, 50);
  assert.equal(rcb.purse, purchased.settings.purse - 50);
  await owner.reload();
  await owner.getByRole("heading", { name: "Lobby Browser Signing", exact: true }).waitFor();
  assert.equal(new URL(owner.url()).searchParams.get("view"), "my-squad");
  assert.equal(await overflow(owner), false);
  await owner.screenshot({ path: resolve(screenshots, "my-squad-1440.png"), fullPage: true });
  console.log("PASS: selecting a player returns to the auction; confirmed sales update My Squad live and survive refresh with correct purse/price.");

  // Home and rejoin must preserve the original host/owner authority, never create another seat.
  for (const [page, access] of [[host, hostAccess], [owner, ownerAccess]]) {
    await page.getByRole("link", { name: "Pavilion home", exact: true }).click();
    await nav(page, "Home").waitFor();
    assert.equal(await nav(page, "Team squads").count(), 0);
    await page.reload();
    await nav(page, "Home").waitFor();
    await page.getByRole("button", { name: "Join a room", exact: true }).click();
    const join = page.getByRole("dialog", { name: "Join auction room", exact: true });
    await join.getByLabel("Your name", { exact: true }).fill("Recovery name");
    await join.getByLabel("Room code", { exact: true }).fill(code);
    await join.getByRole("button", { name: "Join auction room", exact: true }).click();
    await nav(page, "Team squads").waitFor({ state: "attached" });
    assert.deepEqual(await roomAccess(page, code), access, "rejoining must retain the exact original credential");
  }
  assert.equal((await roomState(hostAccess)).members.length, 2);
  assert.equal(await nav(host, "My Squad").count(), 0, "the auctioneer must not have a personal squad navigation item");
  assert.equal(await nav(host, "Build my XI").count(), 0, "the auctioneer must not have a lineup editor navigation item");
  await host.goto(`${base}/?room=${code}&view=my-squad`);
  await host.locator(".app-shell.in-auction.tab-room").waitFor();
  assert.equal(new URL(host.url()).searchParams.get("view"), "room");
  assert.equal(await host.locator(".personal-squad-player").count(), 0, "auctioneers must not see someone else's roster as their own");
  console.log("PASS: returning Home/rejoining preserves both the auctioneer and bidder seats without duplicate members.");

  // A spectator has no personal roster; compact navigation remains usable on mobile.
  const { page: spectator } = await context(390);
  await spectator.goto(`${base}/?room=${code}`);
  dialog = spectator.getByRole("dialog", { name: "Join auction room", exact: true });
  await dialog.getByLabel("Your name", { exact: true }).fill("Browser Spectator");
  await dialog.getByRole("button", { name: "Join auction room", exact: true }).click();
  await spectator.locator(".in-auction").waitFor();
  await clickNav(spectator, "My Squad");
  await spectator.getByRole("heading", { name: "You’re watching from the pavilion.", exact: true }).waitFor();
  assert.equal(await spectator.locator(".personal-squad-player").count(), 0);
  assert.equal(await overflow(spectator), false);
  await spectator.getByRole("link", { name: "Pavilion home", exact: true }).click();
  await spectator.locator(".in-lobby").waitFor();
  await spectator.locator(".cinematic-cast-player img").evaluateAll(images => Promise.all(images.map(image => image.decode())));
  await spectator.evaluate(() => document.fonts.ready);
  assert.equal(await spectator.locator(".cinematic-cast-player img").count(), 8);
  assert.equal(await overflow(spectator), false);
  await spectator.screenshot({ path: resolve(screenshots, "lobby-home-390.png"), fullPage: true });
  await owner.setViewportSize({ width: 390, height: 844 });
  await clickNav(owner, "My Squad");
  await owner.getByRole("heading", { name: "Lobby Browser Signing", exact: true }).waitFor();
  assert.equal(await overflow(owner), false);
  await owner.screenshot({ path: resolve(screenshots, "my-squad-390.png"), fullPage: true });
  assert.deepEqual(errors, []);
  assert.equal(requests.filter(request => /\.(mp4|webm)$/.test(request.url)).length, 0);
  console.log("PASS: spectator privacy, mobile Home/My Squad/navigation, eight-player poster, no video requests or browser errors.");
} finally {
  await browser.close();
  database.close();
}
